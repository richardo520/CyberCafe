#include "Customers/RegularCustomerConversation.h"

FString RegularCustomerConversation::Reply(FName Topic, int32 Turn)
{
    static const TCHAR* Night[] = {
        TEXT("离开维修站以后，我最想做的事，反而是找个地方坐下来。不用马上回答谁，也不用盯着下一盏故障灯。像现在这样就很好。"),
        TEXT("有时候修好一台机器，大家只会记得它又能用了。我倒会记得最后关上工具柜时的那一下轻响，像夜班终于有了句号。"),
        TEXT("下次休息，我想去没有机器响的地方走走。还没决定去哪儿，先把这段空闲留出来，已经有点期待了。"),
        TEXT("维修站里的学徒总怕自己做得太慢。我跟他说，肯停下来把问题看清楚，也是一种本事。其实这话我自己也该多听听。"),
        TEXT("刚来这里时，我总想着喝完就走。现在好像不那么着急了。有个人肯听这些不算大事的小事，夜班也没那么长。"),
        TEXT("如果明天又是忙碌的夜班，我想至少记住现在这种感觉。不是每段时间都得拿来赶路，坐着聊聊天也算没有白过。")
    };
    static const TCHAR* City[] = {
        TEXT("这座城的霓虹总在催人往前走。不过坐在这里看，颜色慢慢从杯子边缘滑过去，街道好像也愿意等一会儿了。"),
        TEXT("我喜欢看街边还留着旧招牌的小店。新的灯当然也好，只是那些磨掉一点颜色的字，会让我想知道以前谁在这里停过。"),
        TEXT("有时候经过高架桥下面，会听见不同方向的脚步声。每个人都有自己的去处，偶尔在同一家店里歇一会儿，也挺奇妙的。"),
        TEXT("如果能给这座城留个安静的角落，我希望那里有长椅，也有不催人走的灯。让赶了一路的人知道，停下来也没关系。"),
        TEXT("我以前只记得从维修站回去的路线。和你聊了这些以后，倒开始留意路边的店了。原来熟悉的路上，也有没认真看过的东西。"),
        TEXT("城市里值得记住的，好像不一定是最高的楼。有时只是有人替你留着座位，或者肯听你把一句话慢慢说完。")
    };
    const int32 Index = FMath::Max(0, Turn) % UE_ARRAY_COUNT(Night);
    return Topic == TEXT("City") ? City[Index] : Night[Index];
}
